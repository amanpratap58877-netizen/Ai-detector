"""
Automated downloader and builder for the balanced multi-domain, multi-generator AI text corpus.
Downloads open-license datasets from official repositories (HuggingFace, RAID).
Zero text is written or generated by AI during this process.
"""

import os
import re
import json
import hashlib
import urllib.request
import pandas as pd

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
os.makedirs(DATA_DIR, exist_ok=True)

OUTPUT_JSON = os.path.join(DATA_DIR, "training_corpus.json")
OUTPUT_CSV = os.path.join(DATA_DIR, "training_corpus.csv")
MANIFEST_MD = os.path.join(DATA_DIR, "CORPUS_MANIFEST.md")

HEADERS = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AI-Detector/2.0"}


def clean_text(text: str) -> str:
    if not isinstance(text, str):
        return ""
    # Normalize unicode quotes and dashes
    t = text.replace("“", '"').replace("”", '"').replace("‘", "'").replace("’", "'")
    t = re.sub(r"\s+", " ", t).strip()
    return t


def fetch_hf_rows(dataset: str, config: str = "default", split: str = "train", offset: int = 0, limit: int = 100):
    encoded_ds = urllib.parse.quote(dataset, safe="")
    url = f"https://datasets-server.huggingface.co/rows?dataset={encoded_ds}&config={config}&split={split}&offset={offset}&limit={limit}"
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=15) as resp:
        return json.loads(resp.read().decode("utf-8"))


def load_raid_samples(target_count=1200):
    """RAID Benchmark: Academic abstracts and attacked/paraphrased generations (MIT License)."""
    raid_path = os.path.join(DATA_DIR, "raid_dataset.csv")
    if not os.path.exists(raid_path):
        print("  [RAID] raid_dataset.csv not found, skipping.")
        return []
    
    print("  [RAID] Loading academic abstracts from local RAID benchmark...")
    df = pd.read_csv(raid_path)
    samples = []
    
    human_df = df[df["model"] == "human"].dropna(subset=["generation"])
    ai_df = df[df["model"] != "human"].dropna(subset=["generation"])
    
    per_class = target_count // 2
    for _, row in human_df.head(per_class).iterrows():
        t = clean_text(row["generation"])
        if len(t.split()) >= 30:
            samples.append({
                "text": t,
                "label": 0,
                "domain": "abstracts",
                "generator": "human",
                "attack": "none",
                "dataset": "RAID Benchmark 2024 (NeurIPS/ACL)",
                "license": "MIT"
            })
            
    for _, row in ai_df.head(per_class).iterrows():
        t = clean_text(row["generation"])
        if len(t.split()) >= 30:
            samples.append({
                "text": t,
                "label": 1,
                "domain": "abstracts",
                "generator": str(row["model"]).lower(),
                "attack": str(row.get("attack", "none")),
                "dataset": "RAID Benchmark 2024 (NeurIPS/ACL)",
                "license": "MIT"
            })
            
    print(f"  [RAID] Collected {len(samples)} samples (Human: {sum(s['label']==0 for s in samples)}, AI: {sum(s['label']==1 for s in samples)})")
    return samples


def load_hc3_samples(target_count=1200):
    """HC3: Human vs ChatGPT comparison corpus (CC-BY-SA 4.0 / Apache-2.0)."""
    print("  [HC3] Downloading paired human vs ChatGPT Q&A answers from HuggingFace...")
    samples = []
    offset = 0
    batch_size = 100
    sub_count = target_count // 2
    
    while (sum(s['label']==0 for s in samples) < sub_count or sum(s['label']==1 for s in samples) < sub_count) and offset < 1000:
        try:
            data = fetch_hf_rows("Hello-SimpleAI/HC3", config="all", split="train", offset=offset, limit=batch_size)
            rows = data.get("rows", [])
            if not rows:
                break
            for r in rows:
                row_data = r.get("row", {})
                for h in row_data.get("human_answers", []):
                    t = clean_text(h)
                    if len(t.split()) >= 30 and sum(s['label']==0 for s in samples) < sub_count:
                        samples.append({
                            "text": t,
                            "label": 0,
                            "domain": "forum_qa",
                            "generator": "human",
                            "attack": "none",
                            "dataset": "HC3 (Human ChatGPT Comparison Corpus)",
                            "license": "CC-BY-SA-4.0"
                        })
                for a in row_data.get("chatgpt_answers", []):
                    t = clean_text(a)
                    if len(t.split()) >= 30 and sum(s['label']==1 for s in samples) < sub_count:
                        samples.append({
                            "text": t,
                            "label": 1,
                            "domain": "forum_qa",
                            "generator": "chatgpt",
                            "attack": "none",
                            "dataset": "HC3 (Human ChatGPT Comparison Corpus)",
                            "license": "CC-BY-SA-4.0"
                        })
            offset += batch_size
        except Exception as e:
            print(f"  [HC3] Fetch batch stopped at offset {offset}: {e}")
            break
            
    print(f"  [HC3] Collected {len(samples)} samples (Human: {sum(s['label']==0 for s in samples)}, AI: {sum(s['label']==1 for s in samples)})")
    return samples


